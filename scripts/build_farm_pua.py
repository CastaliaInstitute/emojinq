# ── geometry ──────────────────────────────────────────────────────────

def catmull_rom(pts, samples_per_seg=14, closed=False):
    if closed:
        ext = [pts[-1]] + list(pts) + [pts[0], pts[1]]
    else:
        ext = [pts[0]] + list(pts) + [pts[-1]]
    out = []
    for i in range(1, len(ext) - 2):
        p0, p1, p2, p3 = ext[i - 1], ext[i], ext[i + 1], ext[i + 2]
        for s in range(samples_per_seg):
            t = s / samples_per_seg
            t2, t3 = t * t, t * t * t
            x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t +
                       (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 +
                       (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t +
                       (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 +
                       (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            out.append((x, y))
    if not closed:
        out.append(tuple(pts[-1]))
    return out


def interp_widths(widths, n):
    if len(widths) == 1:
        return [widths[0]] * n
    out = []
    for i in range(n):
        t = i / (n - 1) * (len(widths) - 1)
        k = min(int(t), len(widths) - 2)
        f = t - k
        out.append(widths[k] * (1 - f) + widths[k + 1] * f)
    return out


def stroke_outline(pts, widths, rng, closed=False, jitter=0.35, wobble=0.08):
    """Centerline + widths → filled outline polygon(s)."""
    center = catmull_rom(pts, closed=closed)
    n = len(center)
    ws = interp_widths(widths, n)
    # tangents → normals
    left, right = [], []
    for i in range(n):
        a = center[max(0, i - 1)] if not closed else center[(i - 1) % n]
        b = center[min(n - 1, i + 1)] if not closed else center[(i + 1) % n]
        dx, dy = b[0] - a[0], b[1] - a[1]
        ln = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / ln, dx / ln
        w = ws[i] * (1 + rng.uniform(-wobble, wobble))
        jx = nx * rng.uniform(-jitter, jitter)
        jy = ny * rng.uniform(-jitter, jitter)
        cx, cy = center[i][0] + jx, center[i][1] + jy
        left.append((cx + nx * w / 2, cy + ny * w / 2))
        right.append((cx - nx * w / 2, cy - ny * w / 2))
    if closed:
        return [left, list(reversed(right))]
    return [left + list(reversed(right))]


def dot(cx, cy, r, rng, segs=10):
    pts = []
    for i in range(segs):
        a = 2 * math.pi * i / segs
        rr = r * (1 + rng.uniform(-0.12, 0.12))
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return [pts]


def poly_to_d(poly):
    d = "M " + " L ".join(f"{x:.2f},{y:.2f}" for x, y in poly) + " Z"
    return d


# ── stroke shorthand ──────────────────────────────────────────────────
# S(points, widths)            open tapered stroke
# L(points, width_or_widths)   closed loop stroke (outline ring)
# D(cx, cy, r)                 filled dot

def S(pts, widths):
    return ("stroke", pts, widths)

def L(pts, widths):
    return ("loop", pts, widths if isinstance(widths, list) else [widths])

def D(cx, cy, r):
    return ("dot", cx, cy, r)

def Cnp(cx, cy, rx, ry, count, wmax):
    """Canopy: a foliage mass built from overlapping brush daubs."""
    return ("canopy", cx, cy, rx, ry, count, wmax)


def canopy_polys(item, rng):
    _, cx, cy, rx, ry, count, wmax = item
    polys = []
    for k in range(count):
        th = 2 * math.pi * k / count + rng.uniform(-0.3, 0.3)
        px = cx + math.cos(th) * rx * 0.55
        py = cy + math.sin(th) * ry * 0.55
        tx, ty = -math.sin(th) * rx, math.cos(th) * ry
        tl = math.hypot(tx, ty) or 1.0
        tx, ty = tx / tl, ty / tl
        ln = (rx * 0.75) * (0.8 + rng.uniform(0, 0.5))
        p1 = (px - tx * ln / 2, py - ty * ln / 2)
        p2 = (px + tx * ln / 2, py + ty * ln / 2)
        w = wmax * (0.75 + rng.uniform(0, 0.35))
        polys.extend(stroke_outline([p1, (px, py), p2], [w * 0.35, w, w * 0.3], rng))
    polys.extend(stroke_outline(
        [(cx - rx * 0.4, cy), (cx, cy - ry * 0.15), (cx + rx * 0.4, cy)],
        [wmax * 0.8, wmax * 1.1, wmax * 0.7], rng))
    return polys


