def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", action="store_true", help="merge entries into assets/pua/manifest.json")
    args = parser.parse_args()
    entries = json.loads(MANIFEST.read_text())
    for category, (start, glyphs) in FAMILIES.items():
        out_dir = ROOT / "assets" / "pua" / category
        out_dir.mkdir(parents=True, exist_ok=True)
        entries = [e for e in entries if not e.get("source", "").startswith(category + "/")]
        for offset, (name, items) in enumerate(glyphs.items()):
            cp = start + offset
            (out_dir / f"{name}.svg").write_text(svg(category, name, cp, strokes(category, name, items)), encoding="utf-8")
            entries.append({
                "name": f"{cp:05X}",
                "source": f"{category}/{name}.svg",
                "codepoints": [cp],
                "label": f"{category}/{name}",
            })
    if args.manifest:
        MANIFEST.write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")
