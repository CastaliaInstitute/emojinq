INK_LIGHT = "#77746a"
STYLE = "sumi-e-ink-wash-v1"
STROKES = "tapered-v1"


def tone(width: float) -> str:
    if width >= 3.0:
        return INK_DARK
    if width >= 1.55:
        return INK_MID
    return INK_LIGHT


def mark(points: list[tuple[float, float]], width: float, seed: str,
         *, loop: bool = False, start: float = 0.22, end: float = 0.14,
         color: str | None = None) -> str:
    if len(points) < 2:
        return ""
    if loop:
        points = points + [points[0]]
        start = end = 0.96
    pressures = []
    for i in range(len(points)):
        t = i / max(1, len(points) - 1)
        # A loaded brush swells before lifting; the small asymmetry avoids a
        # repeated mechanical rhythm across neighboring marks.
        pressure = 0.86 + 0.16 * math.sin(math.pi * t) + 0.05 * math.sin(3.0 * math.pi * t + len(seed))
        pressures.append(BrushPoint(points[i][0], points[i][1], pressure))
    d = stroke_path(pressures, width=width, seed=seed, wobble=0.12,
                    taper_start=start, taper_end=end)
    return f'<path class="ink-wash" d="{d}" fill="{color or tone(width)}" data-ink-brush-pass="v2"/>'


def dot(x: float, y: float, r: float, seed: str, color: str = INK_DARK) -> str:
    points = [(x + r * math.cos(2 * math.pi * i / 10),
               y + r * math.sin(2 * math.pi * i / 10)) for i in range(10)]
    return mark(points, max(1.1, r * 1.35), seed, loop=True, color=color)


def svg(category: str, name: str, codepoint: int, body: str) -> str:
    label = f"{category} / {name}"
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 72 72" role="img"
 aria-label="{label}" data-pua="U+{codepoint:05X}"
 data-castalia-style="{STYLE}" data-ink-stroke-system="{STROKES}"
 data-ink-animation="wash-v1" data-ink-path-units="normalized">
  <title>{label} — naturalist sumi-e brush study</title>
  {body}
</svg>
'''


def strokes(category: str, name: str, items: list[tuple]) -> str:
    # A single subject-specific loaded pass gives the study the weight of ink
    # on paper. It is deliberately a gray brush stroke rather than a universal
    # wash or a second contour; the dark contour and anatomical marks remain
    # visible through the negative space around it.
    mass = DEPTH_STROKES.get((category, name))
    if category == "dinosaurs" and name in DINO_STUDIES:
        items = DINO_STUDIES[name]
    elif category == "sea_creatures" and name in SEA_STUDIES:
        items = SEA_STUDIES[name]
    out = []
    if mass:
        mass_points, mass_width, mass_color = mass
        out.append(mark(mass_points, mass_width, f"{category}/{name}/loaded-body", color=mass_color, start=.48, end=.24))
    for index, item in enumerate(items):
        kind = item[0]
        if kind == "m":
            out.append(mark(item[1], item[2], f"{category}/{name}/{index}", **item[3]))
        elif kind == "d":
            out.append(dot(item[1], item[2], item[3], f"{category}/{name}/{index}", item[4] if len(item) > 4 else INK_DARK))
    return "\n  ".join(out)


def M(points, width, **kwargs):
    return ("m", points, width, kwargs)


def D(x, y, r, color=INK_DARK):
    return ("d", x, y, r, color)


